package app.rasidi.core.help

/**
 * أخطاء مفهومة (على طريقة سَيْل): كل رسالة تتحوّل إلى عنوان قصير، وحلّ بالعربية، وإجراء يفتح المكان المناسب.
 */
object ErrorHelp {
    enum class Action(val label: String) { ACCOUNTS("الحسابات"), RATES("الأسعار"), BACKUP("النسخ الاحتياطي"), GUIDE("الشرح"), SETTINGS("الإعدادات"), NONE("") }
    data class Explained(val title: String, val fix: String, val action: Action, val original: String)

    private data class Rule(val re: Regex, val title: String, val fix: String, val action: Action)

    private val RULES = listOf(
        Rule(Regex("لا يكفي"), "الرصيد لا يكفي", "سجّل دخلاً أو حوّل إلى هذا الحساب أولاً، أو فعّل «السماح بالسالب» إن كان الحساب يدعم السحب.", Action.ACCOUNTS),
        Rule(Regex("يتجاوز المتبقي|تتجاوز أصله"), "المبلغ أكبر من الباقي من الدين", "سجّل الباقي فقط، وما زاد سجّله دخلاً أو ديناً جديداً.", Action.NONE),
        Rule(Regex("بلا سعر|أدخل سعر|سعراً بتاريخ|لا يمكن اعتماد جرد"), "ينقص سعر بتاريخ الجرد", "أدخل سعر العملة أو غرام الذهب بالتاريخ نفسه من «الأسعار»، أو احفظ الجرد مسودة وأكمله لاحقاً.", Action.RATES),
        Rule(Regex("رمز الاستعادة غير صحيح|الرمز غير مكتمل"), "رمز الاستعادة غير صحيح", "اكتبه كما حفظته (الحروف والأرقام، والشرطات اختيارية). الرمز يخص النسخة التي أُنشئت به، وبدونه لا تُفتح.", Action.GUIDE),
        Rule(Regex("ليس نسخة رصيدي|ترويسة الملف تالفة|محتوى النسخة"), "الملف ليس نسخة سليمة من رصيدي", "اختر ملفاً بامتداد .rasidi أُنشئ من رصيدي، أو جرّب نسخة أخرى من Drive.", Action.BACKUP),
        Rule(Regex("صيغة أحدث|إصدار أحدث"), "النسخة من إصدار أحدث من التطبيق", "حدّث رصيدي إلى آخر إصدار ثم أعد الاستعادة.", Action.NONE),
        Rule(Regex("أعد ربط|التفويض|الصلاحية غير كافية"), "يلزم إعادة ربط Google", "افتح «النسخ الاحتياطي» واضغط «أعد ربط Google» ثم وافق.", Action.BACKUP),
        Rule(Regex("خدمات Google Play غير متوفرة"), "خدمات Google غير متوفرة على هذا الهاتف", "استعمل «حفظ نسخة على الهاتف» أو «مشاركة نسخة احتياطية» بدل Drive.", Action.BACKUP),
        Rule(Regex("لا يوجد رمز استعادة|رمز استعادة لهذا الجهاز"), "لم يُنشأ رمز الاستعادة بعد", "أنشئه من «النسخ الاحتياطي» واكتبه خارج الهاتف، ثم أعد المحاولة.", Action.BACKUP),
        Rule(Regex("مجموع الأقساط"), "الأقساط لا تساوي أصل الدين", "عدّل عدد الأقساط أو المبلغ حتى يتساوى المجموع مع أصل الدين.", Action.NONE),
        Rule(Regex("حسابين مختلفين|نفس العملة"), "التحويل يحتاج حسابين مختلفين", "اختر حساب الوجهة غير حساب المصدر. وبنفس العملة يتساوى المبلغان.", Action.NONE),
        Rule(Regex("مهلة التراجع"), "انتهت مهلة التراجع السريع", "افتح الحركة واضغط «عكس الحركة»؛ يبقى الأصل في السجل وتعود الأرصدة.", Action.NONE),
        Rule(Regex("الحساب غير موجود|الدين غير موجود|القطعة غير موجودة"), "العنصر غير موجود", "ربما أُرشف أو استُعيدت نسخة أخرى. حدّث الشاشة واختر من جديد.", Action.NONE),
    )

    fun explain(message: String?): Explained {
        val m = message.orEmpty()
        val r = RULES.firstOrNull { it.re.containsMatchIn(m) }
        return if (r != null) Explained(r.title, r.fix, r.action, m)
        else Explained(m.ifBlank { "حدث خطأ غير متوقع" }, if (m.isBlank()) "أعد المحاولة. وإن تكرر فاحفظ نسخة احتياطية وتواصل مع المطوّر." else "", Action.NONE, m)
    }
}
